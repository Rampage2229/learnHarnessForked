"use client";

import { useMemo, useState } from "react";
import katex from "katex";
import { MATH_SNIPPETS, expandMath, findMathSpans, insertAtCaret } from "@/src/core";
import { cn } from "@/lib/utils";

/**
 * The math composer (math wave, personal fork): the palette + live preview
 * that wraps an existing input. The input STAYS the caller's — this adds:
 *
 * - a **palette row** of the MATH_SNIPPETS entries (compact, the app's
 *   smallest chrome) — clicking one calls onInsert with the returned
 *   {value, caret} from insertAtCaret; the caller owns applying it.
 * - a **live preview** strip: the value's math spans (after expandMath)
 *   rendered through KaTeX, the app's own math engine. Renders only while
 *   the value actually contains math spans — an empty strip on plain prose
 *   would be noise.
 *
 * Presentation only: no state of its own except collapse, no fetches, no
 * storage. The caller keeps input ownership (value, onValueChange,
 * insertion application) — which is what makes this wrappable around the
 * thinking fields without restructuring them.
 */

/** Render one math span (already shorthand-expanded) through KaTeX. */
function renderKatex(tex: string, display: boolean): string {
	try {
		return katex.renderToString(tex, { throwOnError: false, displayMode: display, output: "html" });
	} catch {
		return "";
	}
}

/** The preview's segments: prose between spans stays text; spans render. */
export function mathPreviewSegments(value: string): Array<{ kind: "text" | "math"; text: string; display?: boolean; html?: string }> {
	const spans = findMathSpans(value);
	if (spans.length === 0) return [];
	const out: Array<{ kind: "text" | "math"; text: string; display?: boolean; html?: string }> = [];
	let cursor = 0;
	for (const span of spans) {
		if (span.start > cursor) out.push({ kind: "text", text: value.slice(cursor, span.start) });
		const tex = expandMath(value.slice(span.start, span.end));
		out.push({ kind: "math", text: tex, display: span.display, html: renderKatex(tex, span.display) });
		cursor = span.end;
	}
	if (cursor < value.length) out.push({ kind: "text", text: value.slice(cursor) });
	return out;
}

export function MathComposer({
	value,
	onInsert,
	caretRef,
}: {
	value: string;
	/** Apply an insertion (the caller owns the input's value + caret). */
	onInsert: (next: { value: string; caret: number }) => void;
	/** Where the input's caret currently sits (for insertAtCaret). */
	caretRef?: { current: { start: number; end: number } };
}) {
	const [open, setOpen] = useState(false);
	const segments = useMemo(() => mathPreviewSegments(value), [value]);

	return (
		<div data-testid="math-composer" className="mb-1 flex flex-col gap-1">
			<div className="flex items-center gap-1">
				<button
					type="button"
					data-testid="math-palette-toggle"
					aria-expanded={open}
					onClick={() => setOpen((o) => !o)}
					className="rounded px-1.5 py-0.5 text-[11px] text-muted-foreground transition-colors hover:bg-accent hover:text-foreground"
					title="Math palette"
				>
					∑ ½
				</button>
				{open && (
					<div data-testid="math-palette" className="flex min-w-0 flex-wrap gap-0.5">
						{MATH_SNIPPETS.map((snippet) => (
							<button
								key={snippet.trigger}
								type="button"
								title={`${snippet.label} (${snippet.trigger})`}
								aria-label={snippet.label}
								onClick={() => {
									const caret = caretRef?.current ?? { start: value.length, end: value.length };
									onInsert(insertAtCaret(value, caret.start, snippet.insertion, caret.end));
								}}
								className="rounded px-1.5 py-0.5 text-[11px] text-muted-foreground transition-colors hover:bg-accent hover:text-foreground"
							>
								{snippet.label}
							</button>
						))}
					</div>
				)}
			</div>
			{segments.length > 0 && (
				<div
					data-testid="math-preview"
					className="max-h-24 overflow-y-auto rounded-lg border border-border/60 bg-background/60 px-2 py-1 text-sm"
				>
					{segments.map((segment, i) =>
						segment.kind === "text" ? (
							<span key={i} className="text-muted-foreground">{segment.text}</span>
						) : (
							<span
								key={i}
								className={cn(segment.display && "block text-center")}
								// KaTeX output is trusted markup generated by the app
								// from the learner's TeX (throwOnError: false) — the
								// same trust the transcript's renderer already applies.
								dangerouslySetInnerHTML={{ __html: segment.html ?? "" }}
							/>
						),
					)}
				</div>
			)}
		</div>
	);
}
